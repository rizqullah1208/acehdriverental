/**
 * Helper to look up translation text and interpolate {placeholders}.
 * @param {'id' | 'en'} lang
 * @param {string} path
 * @param {Record<string, string | number>} [vars]
 * @returns {string}
 */
export function t(lang, path, vars = {}) {
  const parts = path.split('.');
  /** @type {any} */
  let node = I18N[lang] || I18N.id;
  for (const part of parts) {
    node = node?.[part];
  }
  let text = typeof node === 'string' ? node : path;
  for (const [k, v] of Object.entries(vars)) {
    text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}
